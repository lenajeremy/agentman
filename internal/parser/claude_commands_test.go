// Records captured from Claude Code 2.1.311 typing commands into its prompt.
// A command was dropped whole, so a person who ran /context from their phone
// saw nothing come back.

func claudeLocalCommand(uuid, content string) obj {
	return obj{"type": "system", "subtype": "local_command", "uuid": uuid, "level": "info",
		"timestamp": "2026-08-10T10:00:00.000Z", "content": content}
}

func TestClaudeCommandsShowWhatWasTypedAndWhatItPrinted(t *testing.T) {
	caveat := claudeUser("u0", "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>")
	caveat["isMeta"] = true
	expanded := claudeUser("u5", "Reply with just the word hi and nothing else. Ada")
	expanded["isMeta"] = true

	path := writeFixture(t, []any{
		caveat,
		// Written as the person's own message by some versions...
		claudeUser("u1", "<command-name>/rename</command-name>\n            <command-message>rename</command-message>\n            <command-args>lab test</command-args>"),
		claudeUser("u2", "<local-command-stdout>Session renamed to: lab test</local-command-stdout>"),
		// ...and as a system record by others, with the terminal's colours.
		claudeLocalCommand("s1", "<command-name>/context</command-name>\n            <command-message>context</command-message>\n            <command-args></command-args>"),
		claudeLocalCommand("s2", "<local-command-stdout> \x1b[1mContext Usage\x1b[22m\n\x1b[38;5;244m⛁ \x1b[38;5;246m⛶ ⛶\x1b[39m  Opus 5.5\n\x1b[38;5;246m⛶ ⛶ ⛶\x1b[39m  34.6k/1m tokens (3%)</local-command-stdout>"),
		// A command that prints nothing leaves no step.
		claudeLocalCommand("s3", "<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>"),
		claudeLocalCommand("s4", "<local-command-stdout></local-command-stdout>"),
		// A prompt command names itself first, and its prompt is hidden.
		claudeUser("u4", "<command-message>hello</command-message>\n<command-name>/hello</command-name>\n<command-args>Ada</command-args>"),
		expanded,
		claudeAssistant("a1", []any{obj{"type": "text", "text": "hi"}}),
		// Shell mode.
		claudeUser("u6", "<bash-input>git status --short</bash-input>"),
		claudeUser("u7", "<bash-stdout> M main.go\n?? notes.md</bash-stdout><bash-stderr></bash-stderr>"),
		claudeUser("u8", "<bash-input>/usage</bash-input>"),
		claudeUser("u9", "<bash-stdout></bash-stdout><bash-stderr>(eval):1: no such file or directory: /usage\n</bash-stderr>"),
		claudeLocalCommand("s5", "<local-command-stderr>Unknown skill: nope</local-command-stderr>"),
	})

	msgs := pageAll(t, path, NewClaudeParser("claude:s"), 40)
	var got []string
	for _, m := range msgs {
		line := string(m.Role) + " " + m.ID + " " + m.Text
		if m.Tool != nil {
			line = string(m.Role) + " " + m.ID + " " + m.Tool.Name + "[" + string(m.Tool.Status) + "] " + m.Tool.Title + " | " + strings.ReplaceAll(m.Text, "\n", "⏎")
		}
		got = append(got, line)
	}
	want := []string{
		"user u1 /rename lab test",
		"tool u2 Command[ok] Session renamed to: lab test | ",
		"user s1 /context",
		"tool s2 Command[ok] Context Usage |  Context Usage⏎⛁ ⛶ ⛶  Opus 5.5⏎⛶ ⛶ ⛶  34.6k/1m tokens (3%)",
		"user s3 /clear",
		"user u4 /hello Ada",
		"assistant a1:0 hi",
		"user u6 !git status --short",
		"tool u7 Bash[ok] M main.go |  M main.go⏎?? notes.md",
		"user u8 !/usage",
		"tool u9 Bash[error] (eval):1: no such file or directory: /usage | ",
		"tool s5 Command[error] Unknown skill: nope | ",
	}
	if strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Errorf("rows:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
	for _, m := range msgs {
		if m.Role == protocol.RoleTool && m.Tool != nil && strings.Contains(m.Text+m.Tool.Title, "\x1b") {
			t.Errorf("row %s kept the terminal's escape codes: %q", m.ID, m.Text)
		}
	}
}

// Scaffolding that is not a command stays out, as before.
func TestClaudeHookScaffoldingStaysOut(t *testing.T) {
	path := writeFixture(t, []any{
		claudeUser("u1", "<user-prompt-submit-hook>extra context</user-prompt-submit-hook>"),
		claudeUser("u2", "hello"),
	})
	msgs := pageAll(t, path, NewClaudeParser("claude:s"), 10)
	if len(msgs) != 1 || msgs[0].Text != "hello" {
		t.Fatalf("got %+v", msgs)
	}
}
