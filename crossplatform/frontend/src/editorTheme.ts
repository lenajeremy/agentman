// Monaco's colours from the app's palette, as the Mac app's EditorTheme
// (desktop/Agentman/Editor/MonacoView.swift) makes them, for one appearance.

type Pair = [light: string, dark: string];

const P = {
  paper: ["#FAFAFA", "#000000"],
  surface: ["#FFFFFF", "#0D0D0D"],
  fill: ["#EFEFEF", "#202020"],
  line: ["#E5E5E5", "#242424"],
  text: ["#101010", "#F2F2F2"],
  textSecondary: ["#3C3C3C", "#D0D0D0"],
  muted: ["#737373", "#A0A0A0"],
  faint: ["#999999", "#737373"],
  working: ["#3268F5", "#578CFF"],
  workingText: ["#1F35C7", "#9DAAFF"],
  needsYou: ["#FF6A2B", "#FF7D45"],
  ok: ["#12A66A", "#2BC784"],
  error: ["#E5484D", "#FF6B70"],
  errorText: ["#C4343A", "#FF8A8E"],
  gitModified: ["#A8690F", "#E2B45C"],
  codeKeyword: ["#8E3BB8", "#D19AF5"],
  codeString: ["#1C7F4B", "#7FD3A0"],
  codeNumber: ["#B25A12", "#F2A867"],
  codeComment: ["#8A8D94", "#6E727B"],
  codeType: ["#1F5FB8", "#8DB8F5"],
  codeFunction: ["#8A6100", "#E8D08A"],
  codeProperty: ["#0E6F8A", "#86D1E3"],
} satisfies Record<string, Pair>;

export function editorTheme(dark: boolean) {
  const c = (name: keyof typeof P, alpha = 1) => {
    const hex = P[name][dark ? 1 : 0];
    return alpha === 1 ? hex : hex + Math.round(alpha * 255).toString(16).padStart(2, "0").toUpperCase();
  };
  const clear = "#00000000";
  const colors: Record<string, string> = {
    "editor.background": c("paper"),
    "editor.foreground": c("text"),
    "editorGutter.background": c("paper"),
    "editorLineNumber.foreground": c("faint"),
    "editorLineNumber.activeForeground": c("textSecondary"),
    "editor.lineHighlightBackground": c("text", 0.045),
    "editor.lineHighlightBorder": clear,
    "editorCursor.foreground": c("text"),
    "editor.selectionBackground": c("working", 0.25),
    "editor.inactiveSelectionBackground": c("working", 0.14),
    "editor.selectionHighlightBackground": c("working", 0.1),
    "editor.wordHighlightBackground": c("working", 0.1),
    "editor.wordHighlightStrongBackground": c("working", 0.16),
    "editor.findMatchBackground": c("needsYou", 0.4),
    "editor.findMatchHighlightBackground": c("needsYou", 0.18),
    "editorBracketMatch.background": c("working", 0.12),
    "editorBracketMatch.border": clear,
    "editorIndentGuide.background1": c("line"),
    "editorIndentGuide.activeBackground1": c("faint", 0.6),
    "editorWhitespace.foreground": c("faint", 0.5),
    "editorOverviewRuler.border": clear,
    "editorGutter.addedBackground": c("ok"),
    "editorGutter.modifiedBackground": c("gitModified"),
    "editorGutter.deletedBackground": c("error"),
    "editorError.foreground": c("error"),
    "editorWarning.foreground": c("needsYou"),
    "editorInfo.foreground": c("working"),
    "editorLink.activeForeground": c("workingText"),
    "editorCodeLens.foreground": c("muted"),
    "editorWidget.background": c("surface"),
    "editorWidget.foreground": c("text"),
    "editorWidget.border": c("line"),
    "editorHoverWidget.background": c("surface"),
    "editorHoverWidget.border": c("line"),
    "editorSuggestWidget.background": c("surface"),
    "editorSuggestWidget.border": c("line"),
    "editorSuggestWidget.selectedBackground": c("working", 0.12),
    "editorSuggestWidget.highlightForeground": c("workingText"),
    "list.hoverBackground": c("fill"),
    "list.highlightForeground": c("workingText"),
    "input.background": c("paper"),
    "input.border": c("line"),
    "inputOption.activeBorder": c("working"),
    focusBorder: c("working", 0.6),
    "widget.shadow": dark ? "#00000066" : "#0000001F",
    "scrollbarSlider.background": c("text", 0.12),
    "scrollbarSlider.hoverBackground": c("text", 0.2),
    "scrollbarSlider.activeBackground": c("text", 0.28),
    "peekView.border": c("working", 0.6),
    "peekViewTitle.background": c("paper"),
    "peekViewEditor.background": c("paper"),
    "peekViewEditorGutter.background": c("paper"),
    "peekViewResult.background": c("surface"),
    "peekViewEditor.matchHighlightBackground": c("needsYou", 0.3),
    "peekViewResult.matchHighlightBackground": c("needsYou", 0.3),
    "peekViewResult.selectionBackground": c("working", 0.14),
  };
  const syntax: Record<string, string> = {
    text: c("text"),
    comment: c("codeComment"),
    string: c("codeString"),
    "string.escape": c("codeNumber"),
    regexp: c("codeString"),
    number: c("codeNumber"),
    constant: c("codeKeyword"),
    keyword: c("codeKeyword"),
    operator: c("text"),
    type: c("codeType"),
    "type.primitive": c("codeKeyword"),
    function: c("codeFunction"),
    property: c("codeProperty"),
    tag: c("codeKeyword"),
    "delimiter.tag": c("faint"),
    heading: c("codeKeyword"),
    "markup.bold": c("text"),
    "markup.italic": c("text"),
    "markup.strike": c("muted"),
    link: c("codeType"),
    "diff.inserted": c("codeString"),
    "diff.deleted": c("errorText"),
    "diff.changed": c("codeNumber"),
    invalid: c("errorText"),
  };
  return { dark, colors, syntax };
}
