// Writes src/panel/fileIconMap.ts from the Mac app's FileIconMap.swift (itself
// generated from material-icon-theme by desktop/scripts/file-icons.py), so
// both apps pick the same icon for a file. The icons themselves are copied
// into public/assets/files by editor.mjs. Run again when the Mac's map changes.

import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const swift = await readFile(join(here, '../../desktop/Agentman/Design/FileIconMap.swift'), 'utf8')

const maps = {}
let current = null
for (const line of swift.split('\n')) {
  const start = line.match(/static let (\w+): \[String: String\] = \[/)
  if (start) {
    current = start[1]
    maps[current] = {}
    continue
  }
  if (current && /^\s*\]/.test(line)) {
    current = null
    continue
  }
  const entry = current && line.match(/^\s*"((?:[^"\\]|\\.)*)": "((?:[^"\\]|\\.)*)",?$/)
  if (entry) maps[current][JSON.parse(`"${entry[1]}"`)] = JSON.parse(`"${entry[2]}"`)
}
for (const name of ['fileNames', 'extensions', 'folderNames', 'openFolderNames']) {
  if (!maps[name] || !Object.keys(maps[name]).length) throw new Error(`FileIconMap.swift: no ${name}`)
}

const out = `// Generated by scripts/file-icons.mjs from desktop/Agentman/Design/FileIconMap.swift
// (material-icon-theme, MIT). Don't edit.

export const fileNames: Record<string, string> = ${JSON.stringify(maps.fileNames)};
export const extensions: Record<string, string> = ${JSON.stringify(maps.extensions)};
export const folderNames: Record<string, string> = ${JSON.stringify(maps.folderNames)};
export const openFolderNames: Record<string, string> = ${JSON.stringify(maps.openFolderNames)};
`
await writeFile(join(here, '../src/panel/fileIconMap.ts'), out)
console.log('src/panel/fileIconMap.ts written')
